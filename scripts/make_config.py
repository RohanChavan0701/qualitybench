"""
make_config.py - Derive a run config (smoke or final) from the base config.

Only the settings passed on the command line change; prompt, max_new_tokens and
backend list stay as in the base file, so every run uses the same measurement
settings. Tracking is turned off: result JSON files are the record.

Usage:
    python scripts/make_config.py --out configs/smoke.yaml \\
        --revision "$(cat results/model_revision.txt)" \\
        --warmup 1 --runs 3 --mmlu-samples 5 --truthfulqa-samples 5

    python scripts/make_config.py --out configs/final.yaml \\
        --revision "$(cat results/model_revision.txt)" \\
        --warmup 3 --runs 100 --mmlu-samples 50 --truthfulqa-samples 200 \\
        --gpu "A100-SXM4-40GB" --gpu-memory-gb 40 --platform "Lambda Cloud"
"""

import argparse
import subprocess

import yaml


def query_gpu(field: str) -> str:
    try:
        out = subprocess.check_output(
            ["nvidia-smi", f"--query-gpu={field}", "--format=csv,noheader,nounits"], timeout=10
        )
        return out.decode().strip().splitlines()[0]
    except Exception:
        return ""


def cuda_version() -> str:
    try:
        out = subprocess.check_output(["nvcc", "--version"], timeout=10).decode()
        return out.strip().splitlines()[-1]
    except Exception:
        return ""


def main():
    parser = argparse.ArgumentParser(description="Write a run config derived from the base config")
    parser.add_argument("--base", default="configs/benchmark_config.yaml")
    parser.add_argument("--out", required=True)
    parser.add_argument("--revision", required=True, help="Hub commit hash of the model")
    parser.add_argument("--warmup", type=int, required=True)
    parser.add_argument("--runs", type=int, required=True)
    parser.add_argument("--mmlu-samples", type=int, required=True, help="Per MMLU subtask (57 subtasks)")
    parser.add_argument("--truthfulqa-samples", type=int, required=True)
    parser.add_argument("--gpu", default=None, help="Default: nvidia-smi name")
    parser.add_argument("--gpu-memory-gb", type=int, default=None, help="Default: nvidia-smi total")
    parser.add_argument("--platform", default="Lambda Cloud")
    args = parser.parse_args()

    with open(args.base) as f:
        config = yaml.safe_load(f)

    config["model"]["revision"] = args.revision
    config["profiling"]["num_warmup_runs"] = args.warmup
    config["profiling"]["num_benchmark_runs"] = args.runs
    config["eval"]["mmlu"]["num_samples"] = args.mmlu_samples
    config["eval"]["truthfulqa"]["num_samples"] = args.truthfulqa_samples
    config["tracking"]["backend"] = "none"

    gpu_mem = args.gpu_memory_gb
    if gpu_mem is None:
        total_mib = query_gpu("memory.total")
        gpu_mem = round(float(total_mib) / 1024) if total_mib else 0
    config["hardware"] = {
        "gpu": args.gpu or query_gpu("name") or "unknown",
        "gpu_memory_gb": gpu_mem,
        "platform": args.platform,
        "cuda_version": cuda_version(),
        "driver_version": query_gpu("driver_version"),
    }

    with open(args.out, "w") as f:
        f.write(f"# Generated by scripts/make_config.py from {args.base}; do not edit by hand.\n")
        yaml.safe_dump(config, f, sort_keys=False, width=100)
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
